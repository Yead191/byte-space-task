export async function getCourseDetailBySlug(
  slug: string
): Promise<CourseDetail | null> {
  const normalizedSlug = decodeURIComponent(slug).toLowerCase().trim();

  // If matching our primary showcase course or id
  if (
    normalizedSlug === "build-digital-asset" ||
    normalizedSlug === "course-2" ||
    normalizedSlug === "build-digital-asset-a-comprehensive-guide"
  ) {
    return BUILD_DIGITAL_ASSET_DETAIL;
  }

  // Find if another course exists in COURSES_DATA
  const matchedCourse = COURSES_DATA.find(
    (c) =>
      c.slug?.toLowerCase() === normalizedSlug ||
      c.id.toLowerCase() === normalizedSlug
  );

  if (matchedCourse) {
    return {
      ...BUILD_DIGITAL_ASSET_DETAIL,
      id: matchedCourse.id,
      slug: matchedCourse.slug || matchedCourse.id,
      title: `${matchedCourse.title}: A Comprehensive Guide`,
      instructor: matchedCourse.instructor,
      level: matchedCourse.level,
      rating: matchedCourse.rating,
      price: matchedCourse.price,
      period: matchedCourse.period || "lifetime",
      videoThumbnail: matchedCourse.image,
    };
  }

  // Default fallback to showcase data to ensure any course-card click renders smoothly
  return BUILD_DIGITAL_ASSET_DETAIL;
}
